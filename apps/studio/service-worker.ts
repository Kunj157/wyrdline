/**
 * The Studio's service worker, generated at build time with the list of
 * every built file: after the first visit Studio itself loads with no
 * network (plan §19 Phase 11), so a bundle can be opened anywhere.
 *
 * - install: precache the app shell and every asset (the WebAssembly
 *   module included, even though the page loads it lazily);
 * - navigations: network first, the cached app shell when offline;
 * - assets: cache first (their names carry a content hash);
 * - the daemon API (`v1/`) and bundles served by `wyrd open` (`bundle/`)
 *   are never cached.
 */
import { createHash } from "node:crypto";
import { readdirSync } from "node:fs";
import { join, relative } from "node:path";

import type { Plugin } from "vite";

/** The worker's source for `assets` (paths relative to the Studio base). */
export function serviceWorkerSource(assets: string[]): string {
  const list = [...new Set(assets)].sort();
  const version = createHash("sha256").update(list.join("\n")).digest("hex").slice(0, 16);
  return `// Generated by apps/studio/service-worker.ts — do not edit.
const CACHE = "wyrd-studio-${version}";
const ASSETS = ${JSON.stringify(list)};
const scope = () => new URL(self.registration.scope);

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches
      .open(CACHE)
      .then((cache) => cache.addAll(["./", ...ASSETS]))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(
          keys
            .filter((k) => k.startsWith("wyrd-studio-") && k !== CACHE)
            .map((k) => caches.delete(k)),
        ),
      )
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;
  const url = new URL(request.url);
  const base = scope();
  if (url.origin !== base.origin || !url.pathname.startsWith(base.pathname)) return;
  const path = url.pathname.slice(base.pathname.length);
  if (path.startsWith("v1/") || path.startsWith("bundle/")) return;
  if (request.mode === "navigate") {
    event.respondWith(
      fetch(request).catch(() =>
        caches.match(base.href).then((hit) => hit || Response.error()),
      ),
    );
    return;
  }
  event.respondWith(caches.match(request).then((hit) => hit || fetch(request)));
});
`;
}

function files(dir: string, root = dir): string[] {
  return readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
    e.isDirectory() ? files(join(dir, e.name), root) : [relative(root, join(dir, e.name))],
  );
}

/** Emit `sw.js` next to `index.html` in production builds. */
export function serviceWorker(publicDir: string): Plugin {
  return {
    name: "wyrd-service-worker",
    apply: "build",
    generateBundle(_options, bundle) {
      const built = Object.keys(bundle).filter((f) => !f.endsWith(".map") && f !== "index.html");
      this.emitFile({
        type: "asset",
        fileName: "sw.js",
        source: serviceWorkerSource([...built, ...files(publicDir)]),
      });
    },
  };
}
