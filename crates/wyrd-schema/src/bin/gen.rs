//! Regenerates the TypeScript types and the JSON Schema for the event schema.
//!
//! Usage: `wyrd-gen-schemas <repo-root>`

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use ts_rs::TS;

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let root = PathBuf::from(std::env::args().nth(1).unwrap_or_else(|| ".".into()));

    let ts_dir = root.join("packages/schemas/src/generated");
    if ts_dir.exists() {
        std::fs::remove_dir_all(&ts_dir)?;
    }
    std::fs::create_dir_all(&ts_dir)?;
    let cfg = ts_rs::Config::new().with_out_dir(&ts_dir);
    wyrd_schema::Event::export_all(&cfg)?;

    let mut names: Vec<String> = std::fs::read_dir(&ts_dir)?
        .filter_map(Result::ok)
        .filter_map(|e| e.file_name().into_string().ok())
        .filter(|n| Path::new(n).extension().is_some_and(|e| e == "ts") && n != "index.ts")
        .collect();
    names.sort();
    let mut index = String::from("// Generated by wyrd-gen-schemas. Do not edit.\n");
    for n in &names {
        let stem = n.trim_end_matches(".ts");
        writeln!(index, "export type {{ {stem} }} from \"./{stem}\";")?;
    }
    write!(
        index,
        "export const SCHEMA_ID = \"{}\";\nexport const KINDS = {} as const;\n",
        wyrd_schema::SCHEMA_ID,
        serde_json::to_string(
            &wyrd_schema::KINDS
                .iter()
                .map(|(k, p)| (k.to_string(), p.as_str()))
                .collect::<std::collections::BTreeMap<_, _>>()
        )?
    )?;
    std::fs::write(ts_dir.join("index.ts"), index)?;

    let schema_dir = root.join("docs/schemas");
    std::fs::create_dir_all(&schema_dir)?;
    let schema = schemars::schema_for!(wyrd_schema::Event);
    let mut json = serde_json::to_string_pretty(&schema)?;
    json.push('\n');
    std::fs::write(schema_dir.join("event.v1.json"), json)?;
    Ok(())
}
