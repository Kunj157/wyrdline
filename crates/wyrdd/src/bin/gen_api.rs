//! Regenerates the daemon API contract: `docs/api/openapi.json` and the
//! TypeScript types in `packages/schemas/src/generated-api/`.
//!
//! Usage: `wyrdd-gen-api <repo-root>`

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use ts_rs::TS;
use wyrdd::api;

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let root = PathBuf::from(std::env::args().nth(1).unwrap_or_else(|| ".".into()));

    let doc_dir = root.join("docs/api");
    std::fs::create_dir_all(&doc_dir)?;
    let mut json = serde_json::to_string_pretty(&wyrdd::openapi::document())?;
    json.push('\n');
    std::fs::write(doc_dir.join("openapi.json"), json)?;

    let ts_dir = root.join("packages/schemas/src/generated-api");
    if ts_dir.exists() {
        std::fs::remove_dir_all(&ts_dir)?;
    }
    std::fs::create_dir_all(&ts_dir)?;
    // Ledger sequence numbers and sizes fit in a JS number (2^53).
    let cfg = ts_rs::Config::new()
        .with_out_dir(&ts_dir)
        .with_large_int("number");
    api::Health::export_all(&cfg)?;
    api::DivergenceList::export_all(&cfg)?;
    api::TriageBody::export_all(&cfg)?;
    api::Ready::export_all(&cfg)?;
    api::SessionList::export_all(&cfg)?;
    api::SessionDetail::export_all(&cfg)?;
    api::EventPage::export_all(&cfg)?;
    api::ToolCallDetail::export_all(&cfg)?;
    api::VerifyReport::export_all(&cfg)?;
    api::Checkpoints::export_all(&cfg)?;
    api::Stopped::export_all(&cfg)?;
    api::PendingAsks::export_all(&cfg)?;
    api::PolicyList::export_all(&cfg)?;
    api::BacktestBody::export_all(&cfg)?;
    api::BacktestReport::export_all(&cfg)?;
    api::AnswerBody::export_all(&cfg)?;
    api::Answered::export_all(&cfg)?;
    api::BranchCreated::export_all(&cfg)?;
    api::Relaunching::export_all(&cfg)?;
    api::Changes::export_all(&cfg)?;
    api::FileDiff::export_all(&cfg)?;
    api::OtlpExportResponse::export_all(&cfg)?;
    api::RewindBody::export_all(&cfg)?;
    api::ForkBody::export_all(&cfg)?;
    api::ApplyBody::export_all(&cfg)?;
    wyrd_cell::apply::ApplyReport::export_all(&cfg)?;
    wyrd_cell::state::CheckpointRecord::export_all(&cfg)?;
    wyrd_correlator::Graph::export_all(&cfg)?;
    wyrd_doctor::Report::export_all(&cfg)?;
    wyrd_adapters::Response::export_all(&cfg)?;
    wyrdd::problem::Problem::export_all(&cfg)?;

    let mut names: Vec<String> = std::fs::read_dir(&ts_dir)?
        .filter_map(Result::ok)
        .filter_map(|e| e.file_name().into_string().ok())
        .filter(|n| Path::new(n).extension().is_some_and(|e| e == "ts") && n != "index.ts")
        .collect();
    names.sort();
    let mut index = String::from("// Generated by wyrdd-gen-api. Do not edit.\n");
    for n in &names {
        let stem = n.trim_end_matches(".ts");
        writeln!(index, "export type {{ {stem} }} from \"./{stem}\";")?;
    }
    std::fs::write(ts_dir.join("index.ts"), index)?;
    Ok(())
}
